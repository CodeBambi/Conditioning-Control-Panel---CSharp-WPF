    /// <summary>Resolves the repo root, the census and the shipping tree. All three are hard
    /// requirements: this guard fails rather than skipping on any of them.</summary>
    private static Reference RequireReference()
    {
        var root = FindRepoRoot();
        Assert.True(root is not null,
            $"repo root not found (anchor: {string.Join('/', RepoAnchorParts)}); this guard never skips");

        var censusPath = Path.Combine(root!, Path.Combine(CensusParts));
        RequirePath(censusPath, isDirectory: false, $"{CensusRelativePath} is missing; this guard never skips");

        var wpf = Path.Combine(root!, Path.Combine(WpfRootParts));
        RequirePath(wpf, isDirectory: true,
            $"{WpfRootParts[0]}/ is missing. The reference tree is IN THIS REPOSITORY, so its absence is a "
            + "corrupt checkout, not an environment this guard may pass in.");

        return new Reference(root!, File.ReadAllText(censusPath), wpf);
    }

    private static void RequirePath(string path, bool isDirectory, string because)
    {
        var present = isDirectory ? Directory.Exists(path) : File.Exists(path);
        Assert.True(present, because);
    }

    private static string? FindRepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null)
        {
            if (File.Exists(Path.Combine(dir.FullName, Path.Combine(RepoAnchorParts)))) return dir.FullName;
            dir = dir.Parent;
        }

        return null;
    }

    private static string Resolve(string root, string relative) =>
        Path.Combine(root, relative.Replace('/', Path.DirectorySeparatorChar));

    /// <summary>A censused directory that has gone missing is a HALF-PRESENT reference tree, i.e. a
    /// corrupt checkout, and fails.</summary>
    private static int CountFilesUnder(string wpf, string relative)
    {
        var dir = Resolve(wpf, relative);
        RequirePath(dir, isDirectory: true,
            $"HALF-PRESENT reference tree: {WpfRootParts[0]}/ exists but {relative} does not. Corrupt checkout.");
        return WalkFiles(dir).Count;
    }

    private static IEnumerable<string> TopLevelNamesUnder(string wpf, string relative) =>
        Directory.GetFiles(Resolve(wpf, relative)).Select(p => Path.GetFileName(p)!);

    private static string ReadShippingFile(string wpf, string relative)
    {
        var path = Resolve(wpf, relative);
        RequirePath(path, isDirectory: false, $"HALF-PRESENT reference tree: {relative} is missing");
        return File.ReadAllText(path);
    }

    private static string ReadRepoFile(string root, string relative)
    {
        var path = Resolve(root, relative);
        RequirePath(path, isDirectory: false, $"{relative} is required by this pin and is missing");
        return File.ReadAllText(path);
    }

    private static List<string> UnresolvedRegistryEntries(string wpf)
    {
        var cosmetics = Resolve(wpf, "Resources/cosmetics");
        var text = ReadShippingFile(wpf, "Resources/cosmetics/registry.json");

        var unresolved = new List<string>();
        foreach (Match m in Regex.Matches(text, "\"file\"\\s*:\\s*\"(?<file>[^\"]+)\""))
        {
            var relative = m.Groups["file"].Value.Replace('\\', Path.DirectorySeparatorChar)
                                                 .Replace('/', Path.DirectorySeparatorChar);
            if (!File.Exists(Path.Combine(cosmetics, relative))) unresolved.Add(relative);
        }

        return unresolved;
    }

    /// <summary>Recursive directory walk. Generated-byte directories are skipped; nothing is skipped
    /// by source-file name. Symlinked directories are not followed.</summary>
    private static List<string> WalkFiles(string root)
    {
        var found = new List<string>();
        var stack = new Stack<string>();
        stack.Push(root);

        while (stack.Count > 0)
        {
            var dir = stack.Pop();
            foreach (var child in Directory.GetDirectories(dir))
            {
                if (GeneratedDirectories.Contains(Path.GetFileName(child))) continue;
                if (new DirectoryInfo(child).LinkTarget is not null) continue;
                stack.Push(child);
            }

            found.AddRange(Directory.GetFiles(dir));
        }

        return found;
    }

