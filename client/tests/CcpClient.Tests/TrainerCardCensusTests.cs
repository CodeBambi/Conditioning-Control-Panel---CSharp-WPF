    /// <summary>The correctness trap the packet named. Two producers of ONE deliberately
    /// source-agnostic event disagree about normalisation, and the set that holds the result is
    /// ordinal. Re-derived from all four files so an upstream change reds this rather than leaving a
    /// stale sentence in a document.</summary>
    [Fact]
    public void TheTwoRaiseSites_DisagreeAboutNormalising_AndTheDistinctSetIsOrdinal()
    {
        var reference = RequireReference();

        var intake = ReadShippingFile(reference.Wpf, "Services/Quiz/IntakeHostService.cs");
        var quizWindow = ReadShippingFile(reference.Wpf, "Windows/QuizWindow.xaml.cs");
        var progress = ReadShippingFile(reference.Wpf, "Models/AchievementProgress.cs");
        var bridge = ReadShippingFile(reference.Wpf, "Services/GamificationBridge.cs");

        // Producer A normalises.
        Assert.Contains(NormalisationExpression, intake, StringComparison.Ordinal);

        // Producer B does not: its category is the definition id or the PascalCase enum name.
        Assert.Matches(@"catDef\?\.Id\s*\?\?\s*result\.Category\.ToString\(\)", quizWindow);

        var quizRaise = Regex.Match(quizWindow, @"RaiseQuizCompleted\([^;]*;", RegexOptions.Singleline);
        Assert.True(quizRaise.Success, "QuizWindow no longer raises; the asymmetry may be gone");
        Assert.DoesNotContain("ToLowerInvariant", quizRaise.Value, StringComparison.Ordinal);

        // The distinct set takes no comparer, so it is ordinal and case-sensitive.
        var declaration = Regex.Match(progress, @"HashSet<string>\s+PerfectedQuizCategories[^;]*;");
        Assert.True(declaration.Success, "PerfectedQuizCategories is gone; §5.2 needs re-deriving");
        Assert.DoesNotContain("Comparer", declaration.Value, StringComparison.Ordinal);

        // The consumer adds the raw value.
        Assert.Matches(@"PerfectedQuizCategories\.Add\(e\.Category\)", bridge);

        var declared = ParseKeyValueTable(reference.Census, "### 9.4");
        Assert.Equal("Services/Quiz/IntakeHostService.cs", declared["upstream-normalises"]);
        Assert.Equal("Windows/QuizWindow.xaml.cs", declared["upstream-does-not-normalise"]);
        Assert.Equal("default", declared["distinct-set-comparer"]);
    }

