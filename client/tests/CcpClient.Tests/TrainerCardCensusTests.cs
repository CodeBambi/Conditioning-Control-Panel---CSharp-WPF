/// <summary>
/// SP-127 — the pin under <c>client/docs/trainer-card-census.md</c>.
///
/// <para><b>Why this exists.</b> The port has been wrong about an upstream count five times
/// (haptic sites 8 → 13 → 14 → 18, For You Feed 3 → 9) and every correction came from WIDENING THE
/// SEARCH, never from re-reading the same lines. <see cref="HapticSiteCensusTests"/> says in its own
/// words that "a guard that only checked the document against itself would have passed on all four
/// numbers", so this file follows that rule rather than inventing a second convention for the same
/// job: the document is the DATA and this file is the LOGIC. The directory roots, the needles and
/// the expression patterns live HERE, and every count and every quoted expression is RE-DERIVED from
/// the shipping bytes on every run. Editing the census document can never shrink the search.</para>
///
/// <para><b>What this census found that makes the re-derivation load-bearing.</b> The board row's
/// five directory counts are arithmetically CORRECT as delta counts, and the row is still wrong:
/// <c>Views/Controls/</c>'s "113 new files" is <b>96.5% other features</b> (87 Companion, 16
/// AppSettings, 6 Studio, 4 Trainer Card). A guard that pinned only the total would have agreed with
/// the row forever, so <see cref="TheViewsControlsCount_IsOverwhelminglyNotThisFeature"/> re-derives
/// the SPLIT, which is the number that carries the finding.</para>
///
/// <para><b>Non-vacuous design, and a DELIBERATE DEPARTURE from the two precedent census guards.</b>
/// The repo root is anchored on <c>client/CcpClient.sln</c> (present in every checkout and in a
/// worktree). Root-not-found, a missing census document, <b>and a missing reference tree</b> are all
/// hard FAILURES. <see cref="HapticSiteCensusTests"/> and <c>FypCensusTests</c> instead carry an
/// "unreachable reference tree" branch for a fully-absent <c>ConditioningControlPanel/</c>; this
/// guard does not, for three independent reasons that all point the same way. (1) The SP-127 packet
/// asked for exactly this: a missing reference tree FAILS rather than skips. (2) That tree is
/// in-repo, so the branch is unreachable on every real checkout and buys nothing. (3) The branch's
/// SHAPE — an early return past a filesystem predicate — is a silencing shape that
/// <see cref="VacuousShapeDetector"/> refuses without a disposition in
/// <c>client/tests/floor/vacuous-shape-ledger.json</c>, and that file is outside this packet's write
/// scope. So the branch is not merely unnecessary here, it is unrepresentable: this guard cannot
/// pass without the reference tree, which is a stronger property than the precedent's and never a
/// skip. Filesystem predicates live in the helpers at the bottom for the same reason.</para>
///
/// <para>The fixture facts pin the walker, the parser, the extractor and the document-shape comparer
/// against temp-dir and in-memory inputs, so none of this rests on today's tree happening to
/// agree.</para>
/// </summary>
