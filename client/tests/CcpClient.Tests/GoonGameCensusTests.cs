    /// <summary>Compares a declared table against re-derived values, reporting every disagreement
    /// rather than the first. Shared by the count facts so none of them can drift apart.</summary>
    private void AssertAgrees(
        IReadOnlyDictionary<string, string> declared, IReadOnlyDictionary<string, string> actual, string section)
    {
        var mismatches = new List<string>();
        foreach (var (key, value) in actual)
        {
            var claimed = declared.TryGetValue(key, out var c) ? c : "<absent>";
            _output.WriteLine($"{key}: census {claimed}, derived {value}");
            if (claimed != value) mismatches.Add($"{key}: census says {claimed}, the bytes say {value}");
        }

        foreach (var key in declared.Keys.Where(k => !actual.ContainsKey(k)))
            mismatches.Add($"{key}: census pins it, nothing re-derives it");

        Assert.True(mismatches.Count == 0,
            $"census {section} does not re-derive:" + Environment.NewLine
            + string.Join(Environment.NewLine, mismatches));
    }

    /// <summary>Recursive directory walk. Generated-byte directories are skipped; nothing is skipped
    /// by source-file name. Symlinked directories are not followed.</summary>
    private static List<string> WalkFiles(string root)
    {
        var found = new List<string>();
        var stack = new Stack<string>();
        stack.Push(root);

        while (stack.Count > 0)
        {
            var dir = stack.Pop();
            foreach (var child in Directory.GetDirectories(dir))
            {
                if (GeneratedDirectories.Contains(Path.GetFileName(child))) continue;
                if (new DirectoryInfo(child).LinkTarget is not null) continue;
                stack.Push(child);
            }

            found.AddRange(Directory.GetFiles(dir));
        }

        return found;
    }

