    /// <summary>A type DECLARATION: the keyword preceded only by modifiers, on a code line, with an
    /// upper-case name. Deliberately narrow — a looser pattern matched prose ("record is…", "for",
    /// "code") and polluted the index with tokens that matched everywhere.</summary>
    private static readonly Regex Declaration = new(
        @"^\s*(?:(?:public|internal|private|protected|sealed|static|abstract|partial|readonly|file|new)\s+)*"
        + @"(?:class|struct|interface|enum|record(?:\s+struct)?)\s+([A-Z][A-Za-z0-9_]*)",
        RegexOptions.Compiled);

    /// <summary>
    /// Strips a trailing <c>//</c> comment, respecting string and char literals, and drops lines
    /// that are wholly comment. A block-comment continuation line that does not start with
    /// <c>*</c> is left as CODE: the bias is deliberate, because an over-reported edge is visible
    /// in the closure while an under-reported one is silent, and this census's headline is a claim
    /// that a set of files is NOT reachable.
    /// </summary>
    private static string CodeOf(string line)
    {
        var trimmed = line.TrimStart();
        if (trimmed.StartsWith("//", StringComparison.Ordinal)
            || trimmed.StartsWith("*", StringComparison.Ordinal)
            || trimmed.StartsWith("/*", StringComparison.Ordinal)) return string.Empty;

        var inString = false;
        var inChar = false;
        var verbatim = false;

        for (var i = 0; i < line.Length; i++)
        {
            var c = line[i];
            if (inString)
            {
                if (verbatim)
                {
                    if (c == '"' && i + 1 < line.Length && line[i + 1] == '"') i++;
                    else if (c == '"') { inString = false; verbatim = false; }
                }
                else if (c == '\\') i++;
                else if (c == '"') inString = false;
                continue;
            }

            if (inChar)
            {
                if (c == '\\') i++;
                else if (c == '\'') inChar = false;
                continue;
            }

            if (c == '"')
            {
                inString = true;
                verbatim = i > 0 && (line[i - 1] == '@' || (line[i - 1] == '$' && i > 1 && line[i - 2] == '@'));
                continue;
            }

            if (c == '\'') { inChar = true; continue; }
            if (c == '/' && i + 1 < line.Length && line[i + 1] == '/') return line[..i];
        }

        return line;
    }

    private static HashSet<string> ShippedPathClosure(string wpf)
    {
        var dir = Resolve(wpf, SurfaceDirectory[0]);
        RequirePath(dir, isDirectory: true, $"HALF-PRESENT reference tree: {SurfaceDirectory[0]} is missing");

        var files = RelativeFilesUnder(wpf, SurfaceDirectory[0])
            .ToDictionary(p => p, p => ReadShippingFile(wpf, $"{SurfaceDirectory[0]}/{p}"), StringComparer.Ordinal);

        return CloseOver(files, ShippedPathSeed);
    }

    /// <summary>Transitive closure from <paramref name="seed"/> over the type names each file
    /// declares. Kept separate from the filesystem so the fixture can drive it with synthetic
    /// sources.</summary>
    private static HashSet<string> CloseOver(IReadOnlyDictionary<string, string> files, string seed)
    {
        var typeToFile = new Dictionary<string, string>(StringComparer.Ordinal);
        var codeLines = new Dictionary<string, string[]>(StringComparer.Ordinal);

        foreach (var (path, text) in files)
        {
            var lines = text.Split('\n').Select(l => CodeOf(l.TrimEnd('\r'))).ToArray();
            codeLines[path] = lines;

            var baseName = Path.GetFileNameWithoutExtension(path);
            typeToFile.TryAdd(baseName, path);
            foreach (var line in lines)
            {
                var m = Declaration.Match(line);
                if (m.Success) typeToFile.TryAdd(m.Groups[1].Value, path);
            }
        }

        var needles = typeToFile
            .Select(kv => (Owner: kv.Value, Pattern: new Regex($@"\b{Regex.Escape(kv.Key)}\b", RegexOptions.Compiled)))
            .ToList();

        var closure = new HashSet<string>(StringComparer.Ordinal) { seed };
        var queue = new Queue<string>();
        queue.Enqueue(seed);

        while (queue.Count > 0)
        {
            var current = queue.Dequeue();
            if (!codeLines.TryGetValue(current, out var lines)) continue;

            foreach (var line in lines)
            {
                if (line.Length == 0) continue;
                foreach (var (owner, pattern) in needles)
                {
                    if (owner == current || closure.Contains(owner)) continue;
                    if (!pattern.IsMatch(line)) continue;
                    closure.Add(owner);
                    queue.Enqueue(owner);
                }
            }
        }

        return closure;
    }

