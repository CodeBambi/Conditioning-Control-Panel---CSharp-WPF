    /// <summary>Reads the first two-column table after <paramref name="heading"/>, stopping at the
    /// next heading so sections cannot leak into each other.</summary>
    private static Dictionary<string, string> ParseKeyValueTable(string document, string heading) =>
        ParseTable(document, heading, 2, cells => (cells[0], cells[1]));

    /// <summary>Reads an id/path/kind table, keyed by PATH so the census's own ids never become the
    /// thing under test.</summary>
    private static Dictionary<string, string> ParseIdPathTable(string document, string heading) =>
        ParseTable(document, heading, 2, cells => (cells[1], cells.Count >= 3 ? cells[2] : string.Empty));

    private static Dictionary<string, string> ParseTable(
        string document, string heading, int minimumCells, Func<List<string>, (string Key, string Value)> select)
    {
        var result = new Dictionary<string, string>(StringComparer.Ordinal);
        var lines = document.Split('\n');
        var index = Array.FindIndex(lines, l => l.TrimEnd('\r').StartsWith(heading, StringComparison.Ordinal));
        if (index < 0) return result;

        for (var i = index + 1; i < lines.Length; i++)
        {
            var line = lines[i].Trim();
            if (line.StartsWith("##", StringComparison.Ordinal)) break;
            if (!line.StartsWith('|')) continue;

            var cells = SplitRow(line);
            if (cells.Count < minimumCells) continue;
            if (cells[0] is "Key" or "#" or "Id") continue;
            if (cells[0].Length > 0 && cells[0].All(c => c is '-' or ':')) continue;

            var (key, value) = select(cells);
            result[key] = value;
        }

        return result;
    }

    private static List<CitationRow> ParseCitationTable(string document, string heading) =>
        ParseCitationTable(document, heading, out _);

    private static List<CitationRow> ParseCitationTable(
        string document, string heading, out List<string> unparsed)
    {
        var rows = new List<CitationRow>();
        unparsed = [];
        var lines = document.Split('\n');
        var index = Array.FindIndex(lines, l => l.TrimEnd('\r').StartsWith(heading, StringComparison.Ordinal));
        if (index < 0) return rows;

        for (var i = index + 1; i < lines.Length; i++)
        {
            var line = lines[i].Trim();
            if (line.StartsWith("##", StringComparison.Ordinal)) break;
            if (!line.StartsWith('|')) continue;

            var cells = SplitRow(line);
            if (cells[0] is "Key") continue;
            if (cells[0].Length > 0 && cells[0].All(c => c is '-' or ':')) continue;

            // A ROW THAT DOES NOT PARSE IS REPORTED, NEVER SKIPPED. Skipping is how §10.4 and §10.5
            // leaked: a two-cell narrative row dropped out here silently while its digits still
            // reached the pinned vocabulary — hole five's shape, in the two subsections a
            // three-subsection probe did not reach. Every table row inside a citation pin table
            // must BE a citation.
            if (cells.Count < 4 || !int.TryParse(cells[2], out var lineNumber))
            {
                unparsed.Add($"line {i + 1}: {line}");
                continue;
            }

            // Markdown escapes inside a needle are the DOCUMENT's syntax, not the source's. `\|`
            // would truncate the row and `\*` would italicise the cell, so both are written escaped
            // in the census and unescaped here before the needle is matched against real bytes.
            rows.Add(new CitationRow(cells[0], cells[1], lineNumber,
                cells[3].Replace("\\|", "|").Replace("\\*", "*")));
        }

        return rows;
    }

    private static List<string> SplitRow(string line)
    {
        var trimmed = line.Trim();
        if (trimmed.StartsWith('|')) trimmed = trimmed[1..];
        if (trimmed.EndsWith('|')) trimmed = trimmed[..^1];

        return trimmed.Split('|')
            .Select(c => c.Trim().Trim('`', '*').Trim())
            .ToList();
    }

    private static List<string> BehaviourRows(string document) =>
        document.Split('\n')
            .Select(l => l.Trim())
            .Where(l => Regex.IsMatch(l, @"^\|\s*B\d+\s*\|"))
            .ToList();

    /// <summary>Maximal runs of pipe-rows whose second line is not a GFM delimiter row. Fenced
    /// code blocks are skipped.</summary>
    private static List<string> MalformedTables(string document)
    {
        var bad = new List<string>();
        var lines = document.Split('\n');
        var fenced = false;
        var i = 0;

        while (i < lines.Length)
        {
            var trimmed = lines[i].Trim();
            if (trimmed.StartsWith("```", StringComparison.Ordinal)) { fenced = !fenced; i++; continue; }
            if (fenced || !trimmed.StartsWith('|')) { i++; continue; }

            var start = i;
            while (i < lines.Length)
            {
                var t = lines[i].Trim();
                if (t.StartsWith("```", StringComparison.Ordinal) || !t.StartsWith('|')) break;
                i++;
            }

            var run = i - start;
            var delimiter = run >= 2 && IsDelimiterRow(lines[start + 1]);
            if (!delimiter)
                bad.Add($"line {start + 1}: a run of {run} pipe-row(s) with no delimiter row after the "
                    + $"header — first row reads \"{lines[start].Trim()[..Math.Min(90, lines[start].Trim().Length)]}\"");
        }

        return bad;
    }

    private static bool IsDelimiterRow(string line)
    {
        var cells = SplitRow(line.Trim());
        return cells.Count > 0
            && cells.All(c => c.Length > 0 && c.Contains('-', StringComparison.Ordinal)
                              && c.All(ch => ch is '-' or ':'));
    }

    private static List<string> UnescapedPipesInCodeSpans(string document)
    {
        var offenders = new List<string>();
        var lineNumber = 0;
        foreach (var line in document.Split('\n'))
        {
            lineNumber++;
            if (!line.TrimStart().StartsWith('|')) continue;
            foreach (Match span in Regex.Matches(line, "`[^`]*`"))
                if (span.Value.Contains('|') && !span.Value.Contains("\\|", StringComparison.Ordinal))
                    offenders.Add($"line {lineNumber}: {span.Value}");
        }

        return offenders;
    }

    /// <summary>One decimal place, INVARIANT culture. The first version used the ambient culture and
    /// produced "20,0" on this machine — a guard that would have passed on an en-US box and failed on
    /// a comma-locale one, which is the same class of latent defect this census reports upstream.</summary>
    private static string Percent(long numerator, long denominator) =>
        denominator == 0
            ? "0.0"
            : Math.Round(numerator * 100.0 / denominator, 1).ToString("0.0", CultureInfo.InvariantCulture);
