    /// <summary>Contexts a number may legitimately live in WITHOUT being a claim about this
    /// surface. Each is a CLASS, and each is here in code rather than as a list of literals.</summary>
    private static readonly Regex[] ExcludedNumberClasses =
    [
        new(@"[A-Za-z0-9_.\-]+\.(?:cs|js|mjs|json|xaml|axaml|csproj|md|html|css|webmanifest):\d+(?:-\d+)?", RegexOptions.Compiled), // File.ext:NNN citations
        new(@"(?<![A-Za-z0-9]):\d+(?:-\d+)?", RegexOptions.Compiled),                                                 // bare :NNN continuations
        new(@"§\s*\d+(?:\.\d+)*", RegexOptions.Compiled),                                                             // section references
        new(@"\bD\d+\b", RegexOptions.Compiled),                                                                      // divergence ids
        new(@"\b\d{4}-\d{2}-\d{2}\b", RegexOptions.Compiled),                                                         // ISO dates
        new(@"\bv\d+(?:\.\d+)*\b", RegexOptions.Compiled),                                                            // versions
        new(@"\bsha-?\d+\b", RegexOptions.Compiled | RegexOptions.IgnoreCase),                                        // hash algorithm names
        // A hex sha, and NOT a long decimal. The first version was `[0-9a-f]{7,}` flat, which also
        // matched 12471900 — the payload's own byte total — and quietly dropped it from the
        // vocabulary the moment both sides started stripping classes. At least one a-f is required.
        new(@"\b(?=[0-9a-f]{7,}\b)[0-9a-f]*[a-f][0-9a-f]*\b", RegexOptions.Compiled),                                 // hex shas
        new(@"\bB\d+\b|\bG\d+\b|\bX\d+\b|\bR\d+\b|\bQ\d+\b", RegexOptions.Compiled),                                  // row ids
        new(@"^#{1,6}\s.*$", RegexOptions.Compiled | RegexOptions.Multiline),                                         // headings
    ];

    /// <summary>
    /// The numbers the census is entitled to state: the ones in a §10 pin TABLE ROW, plus the ones
    /// named in §9's "does not prove" section.
    ///
    /// <para><b>Only table rows count inside §10, and this is a repair.</b> The first version
    /// treated every line after the <c>## 10.</c> heading as pinned. §10 is the last section, so
    /// anything appended to the document landed inside it and had its numbers silently added to the
    /// vocabulary. <b>The red demonstration this fact was built with PASSED because of exactly
    /// that</b> — the guard was looking somewhere the claim was not, which is the same shape of hole
    /// the earlier path-only pin had.</para>
    /// </summary>
    private static HashSet<string> PinnedNumbers(string census)
    {
        var vocabulary = new HashSet<string>(StringComparer.Ordinal);

        foreach (var (line, section) in Sections(census))
        {
            // Pins now means a PIN SUBSECTION (§10.1-§10.6), never "anywhere inside §10" — see
            // Sections(). A narrative table inside §10 contributes nothing to the vocabulary.
            var admissible = section == DocumentSection.Disclaimer
                          || (section == DocumentSection.Pins && line.TrimStart().StartsWith('|'));
            if (!admissible) continue;

            // THE SAME CLASS FILTER THE CHECKING SIDE USES, and the reason it is here is a hole
            // this guard shipped once. Harvesting digit runs RAW while UnpinnedNumbers strips
            // classes is an ASYMMETRY, and an asymmetry is the literal-exclusion escape hatch by
            // another route: row ids (G7, G12, G24) and citation line numbers
            // (GoonSignalingClient.cs:16-17) injected 7, 12, 16 and 24 into the vocabulary and
            // whitelisted those integers EVERYWHERE in the document. That is how a stale "16%"
            // survived a green suite. The two sides must strip the same classes or neither does.
            var admitted = line;
            foreach (var excluded in ExcludedNumberClasses) admitted = excluded.Replace(admitted, " ");

            foreach (Match m in Regex.Matches(admitted, @"\d[\d,_ ]*(?:\.\d+)?"))
                vocabulary.Add(Normalize(m.Value));
        }

        return vocabulary;
    }

    private enum DocumentSection { Body, Disclaimer, Pins }

    /// <summary>
    /// Walks the census once, tagging each line with the section it sits in. Shared by both halves
    /// of the number sweep so they can never disagree about where a section ends.
    ///
    /// <para><b><c>Pins</c> means a PIN SUBSECTION, not "anywhere inside §10".</b> §10.7 is
    /// narrative prose that happens to use tables, and it sits inside §10 — so under the previous
    /// rule its own axis table, <i>the table documenting this guard's holes</i>, re-injected the
    /// very integers it was describing back into the pinned vocabulary. The documentation of the
    /// defect recreated the defect. Only <c>### 10.1</c>-<c>### 10.6</c> and their <c>.N</c>
    /// children are pin subsections; everything else inside §10 is Body and is CHECKED like any
    /// other prose.</para>
    /// </summary>
    private static IEnumerable<(string Line, DocumentSection Section)> Sections(string census)
    {
        var section = DocumentSection.Body;
        var inPinSubsection = false;

        foreach (var raw in census.Split('\n'))
        {
            var line = raw.TrimEnd('\r');
            if (line.StartsWith("## ", StringComparison.Ordinal))
            {
                section = Regex.IsMatch(line, @"^##\s+10\.\s") ? DocumentSection.Pins
                        : Regex.IsMatch(line, @"^##\s+9\.\s") ? DocumentSection.Disclaimer
                        : DocumentSection.Body;
                inPinSubsection = false;
            }
            else if (line.StartsWith("### ", StringComparison.Ordinal))
            {
                inPinSubsection = Regex.IsMatch(line, @"^###\s+10\.[1-6](\.\d+)*\b");
            }

            var effective = section == DocumentSection.Pins && !inPinSubsection
                ? DocumentSection.Body
                : section;

            yield return (line, effective);
        }
    }

    /// <summary>Every number outside §9, and inside §10 every number that is NOT in a pin table row,
    /// must already be in the pinned vocabulary. Checking §10's prose as well as the body is what
    /// makes text appended to the end of the document reachable by this fact.</summary>
    private static List<string> UnpinnedNumbers(string census, HashSet<string> pinned)
    {
        var escapees = new List<string>();
        var lineNumber = 0;

        foreach (var (raw, section) in Sections(census))
        {
            lineNumber++;
            if (section == DocumentSection.Disclaimer) continue;
            if (section == DocumentSection.Pins && raw.TrimStart().StartsWith('|')) continue;

            var line = raw;
            foreach (var excluded in ExcludedNumberClasses) line = excluded.Replace(line, " ");

            foreach (Match m in Regex.Matches(line, @"\d[\d,_ ]*(?:\.\d+)?"))
            {
                var value = Normalize(m.Value);
                if (value.Length == 0 || pinned.Contains(value)) continue;
                var trimmed = raw.Trim();
                escapees.Add($"line {lineNumber}: {value} — in \"{trimmed[..Math.Min(110, trimmed.Length)]}\"");
            }
        }

        return escapees;
    }

    /// <summary>Small integers spelled out, so a tally restated in words is comparable with one
    /// re-derived as a number. The census writes verdict tallies in words.</summary>
    private static string NumberWord(int value) => value switch
    {
        0 => "zero", 1 => "one", 2 => "two", 3 => "three", 4 => "four", 5 => "five", 6 => "six",
        7 => "seven", 8 => "eight", 9 => "nine", 10 => "ten", 11 => "eleven", 12 => "twelve",
        _ => value.ToString(CultureInfo.InvariantCulture),
    };

    private static string Normalize(string number) =>
        number.Replace(",", "").Replace("_", "").Replace(" ", "").TrimEnd('.');

