    private static List<string> CitationDrift(IEnumerable<CitationRow> rows, Func<string, string> read)
    {
        var wrong = new List<string>();
        foreach (var row in rows)
        {
            var line = LineAt(read(row.Path), row.Line);
            if (!line.Contains(row.Needle, StringComparison.Ordinal))
                wrong.Add($"{row.Key}: {row.Path}:{row.Line} should carry \"{row.Needle}\" but the line reads \"{line.Trim()}\"");
        }

        return wrong;
    }

    /// <summary>The 1-based line, or empty when out of range. Empty never contains a needle, so an
    /// off-by-one fails rather than silently passing.</summary>
    private static string LineAt(string text, int oneBasedLine)
    {
        var lines = text.Split('\n');
        return oneBasedLine >= 1 && oneBasedLine <= lines.Length ? lines[oneBasedLine - 1] : string.Empty;
    }

