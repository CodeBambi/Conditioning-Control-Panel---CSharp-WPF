    [Fact]
    public void TheFourPrivacyVerdicts_ArePinnedAtTheStartOfTheAnswer()
    {
        var census = RequireReference().Census;
        var wrong = new List<string>();

        foreach (var (id, verdict) in PrivacyVerdicts)
        {
            var row = census.Split('\n')
                .Select(l => l.Trim())
                .FirstOrDefault(l => Regex.IsMatch(l, $@"^\|\s*{id}\s*\|"));
