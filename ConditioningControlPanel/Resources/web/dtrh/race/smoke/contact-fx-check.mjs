import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const threeUrl = new URL('../../../vendor/three/three.module.min.js', import.meta.url);
const THREE = await import(threeUrl.href);
const code = (await readFile(new URL('../contactFx.js', import.meta.url), 'utf8')).replace("from 'three'", 'from '+JSON.stringify(threeUrl.href));
const { createContactFx, CONTACT_CAP } = await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const scene = new THREE.Scene(), fx = createContactFx({scene});
const k={d:98,x:0,h:0,speed:22}; let transforms=0;
const layout={wrap:d=>(d%100+100)%100,surfaceH:()=>2,toWorld(d,x,h,out){transforms++;assert.ok(d>=0&&d<100);return out.set(x,h,d)}};
const lines=scene.getObjectByName('race-contact-sparks');
assert.equal(lines.visible,false,'no new ambient particles');
fx.beat({type:'driftBoost',tier:3},k,layout); fx.update(1/60,layout);
assert.equal(lines.geometry.drawRange.count,120,'tier 3 throws sixty sparks');
assert.equal(transforms,120,'every segment endpoint uses layout.toWorld');
assert.equal(lines.geometry.attributes.position.count,CONTACT_CAP*2,'pool is allocated once');
for(let i=0;i<20;i++)fx.beat({type:'landing',clean:true,impact:1},k,layout);
fx.update(1/60,layout);
assert.ok(lines.geometry.drawRange.count<=CONTACT_CAP*2,'repeated contacts never grow the pool');
assert.ok([...lines.geometry.attributes.position.array].every(Number.isFinite),'wrap and ramp geometry remain finite');
fx.clear();assert.equal(lines.visible,false,'pause clears the whole beat');
fx.update(1/60,layout);assert.equal(lines.geometry.drawRange.count,0,'resume does not replay old particles');
fx.beat({type:'landing',clean:false,impact:0.3},k,layout);
for(let i=0;i<60;i++)fx.update(1/60,layout);
assert.equal(lines.visible,false,'contact is completely settled within one second');
fx.dispose();fx.dispose();assert.equal(scene.children.length,0,'dispose is complete and idempotent');
const quiet=createContactFx({scene,reducedMotion:true});quiet.beat({type:'driftBoost',tier:3},k,layout);quiet.update(1/60,layout);
assert.equal(scene.children[0].visible,false,'reduced motion has no burst');quiet.dispose();
console.log('contact-fx-check: pool, track transforms, pause, reduced motion and disposal passed');
