/* ============================================================================
 * race/gltf.js - Racing Thoughts glTF pack loader.
 *
 * Two packs, both authored in Blender and dropped in race/assets/:
 *
 *   emi.glb    the mascot rig. Nodes: EMI_root, EMI_case, EMI_glass, ant0,
 *              ant1, ant2, ballpiv, shoulderL, shoulderR, footL, footR,
 *              button. Clips: idle, wave, hop, peek, drum. EMI_glass carries
 *              the face atlas (see setFace / FACES). The strip baked into it is
 *              the fallback: loadPack re-points the glass at the sibling
 *              assets/emi-faces.png, which is the one that grows a frame.
 *   props.glb  every prop as a NAMED TOP-LEVEL node: kart_cup, kart_saucer,
 *              item_cube, item_shard_00 .. item_shard_11, boost_pad, ramp_lip,
 *              air_marker, gantry, podium, floor_tile, plus one <room>_<slot>
 *              per roomProps ROOM_PROPS entry (teagarden_wall, casino_shoulder,
 *              toybox_extra, ...).
 *
 * NOTHING here depends on any of those names existing. byName() returns null
 * for a miss and every caller falls back to the hand-built voxel kit, so a
 * half-finished pack degrades one prop at a time instead of blanking the race.
 *
 *   loadPack(url, { log }) -> Promise<Pack>       cached per url
 *   Pack = { scene, animations, byName, clone, names, stats }
 *   toInstanceGeometry(node) -> BufferGeometry    roomProps-shaped, ready for
 *                                                 InstancedMesh + Lambert
 *   setFace(model, index) / FACES / faceFrames(texture)
 *   flattenRig(root, animations, { keep })   one draw per pivot + material
 *   preparePixel(model, pixel)
 *   disposePack(url)
 *   stripBoneScaleTracks(animations)         drops the scale tracks a bone may never have
 *
 * COLOUR SPACE. roomProps voxel() writes Color.setHex(hex).r/g/b into its
 * `color` attribute, and setHex decodes sRGB into the linear working space, so
 * that attribute is LINEAR. glTF agrees: baseColorFactor and COLOR_0 are both
 * linear by spec and GLTFLoader keeps them that way. So the merge below copies
 * material.color / COLOR_0 straight through with no conversion, and a merged
 * prop shades identically to a voxel() one beside it.
 * ==========================================================================*/

import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { mergeGeometries } from 'three/addons/utils/BufferGeometryUtils.js';

/** Face atlas order, left to right across EMI_glass's map. Frames are only ever APPENDED:
 *  the index is the contract every caller quotes (menu.js ROSTER faces, intro.js FACE). */
export const FACES = ['^_^', ':3', '>_<', 'o_o', '$_$', '★_★', '@_@'];
/** Frames in the strip baked into emi.glb. The authored EMI_glass UVs span exactly one of them,
 *  so a wider atlas is a repeat.x of BAKED_FRAMES / FACES.length on top of those UVs. */
const BAKED_FRAMES = 5;
/** The sibling of the .glb: the live strip, regenerated by tools/blender/emi/face2.py --game. */
const FACE_ATLAS = 'emi-faces.png';
const GLASS = 'EMI_glass';
const OUTLINE = 'outline';                 // material name: inverted hull, never re-wound
const MAP_KEYS = ['map', 'emissiveMap', 'alphaMap', 'normalMap', 'roughnessMap', 'metalnessMap', 'aoMap'];

/**
 * Bones no clip may ever scale. A shoulder is a HINGE: the arm under it (armR, handR, thumbR,
 * shoulder_capR) turns, it never grows. emi.glb's `wave` export bakes a y scale on shoulderR that
 * runs up to 2.12, which stretches that whole arm to twice its length and out of the case for the
 * length of the wave (the desktop build shows the same stretch, and every other clip holds both
 * shoulders at 1). The glb belongs to the Blender pipeline, so the fix is here: the scale track is
 * dropped at load and the bone sits at its rest scale of 1 while the rotation does the wave.
 */
export const NO_SCALE_BONES = ['shoulderL', 'shoulderR'];

/**
 * Drop every `.scale` track aimed at one of `bones` from every clip, in place. Rotation and
 * translation are left alone: only the scale is the export mistake. Returns how many tracks went.
 */
export function stripBoneScaleTracks(animations, bones = NO_SCALE_BONES) {
  const want = new Set(bones.map((b) => THREE.PropertyBinding.sanitizeNodeName(b)));
  let dropped = 0;
  for (const clip of animations || []) {
    if (!clip || !Array.isArray(clip.tracks)) continue;
    clip.tracks = clip.tracks.filter((t) => {
      const parsed = t && t.name ? THREE.PropertyBinding.parseTrackName(t.name) : null;
      const hit = parsed && parsed.propertyName === 'scale' && want.has(parsed.nodeName);
      if (hit) dropped++;
      return !hit;
    });
  }
  return dropped;
}

const _cache = new Map();                  // url -> { promise, pack }
const _mat = new THREE.Matrix4();
const _inv = new THREE.Matrix4();

// ---- loading ---------------------------------------------------------------------------

/**
 * Load (or hand back) a pack. One in-flight request per url; a failed load drops out of the
 * cache so a later call can retry. `log` is the race's one-argument logger (bridge.log style).
 */
export function loadPack(url, { log } = {}) {
  const hit = _cache.get(url);
  if (hit) return hit.promise;
  const entry = { promise: null, pack: null };
  entry.promise = new Promise((resolve, reject) => {
    new GLTFLoader().load(url, resolve, undefined, reject);
  }).then((gltf) => {
    const pack = makePack(gltf, url);
    return swapFaceAtlas(pack).then(() => pack);
  }).then((pack) => {
    entry.pack = pack;
    if (log) log(`gltf ${url}: ${pack.stats.nodes} nodes, ${pack.stats.tris} tris, ${(pack.stats.bytes / 1024).toFixed(0)} KB`);
    return pack;
  }).catch((e) => {
    _cache.delete(url);
    if (log) log(`gltf ${url} failed: ${(e && e.message) || e}`);
    throw e;
  });
  _cache.set(url, entry);
  return entry.promise;
}

/**
 * Wrap a parsed gltf. Exported so the node smoke can go through GLTFLoader.parse() without a
 * network fetch; the race itself only ever calls loadPack.
 */
export function makePack(gltf, url = '') {
  const scene = gltf.scene || (gltf.scenes && gltf.scenes[0]) || new THREE.Group();
  const animations = gltf.animations || [];
  stripBoneScaleTracks(animations);       // one choke point: every pack, every clip, every caller
  const index = new Map();
  let nodes = 0, tris = 0;
  scene.traverse((o) => {
    nodes++;
    if (o.name && !index.has(o.name)) index.set(o.name, o);
    const g = o.geometry;
    if (!g || !g.attributes || !g.attributes.position) return;
    tris += (g.index ? g.index.count : g.attributes.position.count) / 3;
  });
  return {
    scene,
    animations,
    url,
    byName: (name) => index.get(name) || null,
    names: () => Array.from(index.keys()),
    clone: (name) => {
      const src = index.get(name);
      return src ? src.clone(true) : null;      // Object3D.clone shares geometry AND material
    },
    stats: { nodes, tris: Math.round(tris), bytes: byteSize(gltf) },
  };
}

/** Best effort source size: the GLB body hangs off the parser on the binary path, so fall back
 *  to the json length rather than guessing when a pack arrives as plain .gltf. */
function byteSize(gltf) {
  const p = gltf.parser;
  const bin = p && p.extensions && p.extensions.KHR_binary_glTF;
  if (bin && bin.body && bin.body.byteLength) return bin.body.byteLength;
  if (p && p.json) { try { return JSON.stringify(p.json).length; } catch (e) { /* cyclic, give up */ } }
  return 0;
}

/** Dispose everything a pack owns and forget it. Safe on an unknown or still-loading url. */
export function disposePack(url) {
  const entry = _cache.get(url);
  if (!entry) return;
  _cache.delete(url);
  const kill = (pack) => {
    if (!pack || !pack.scene) return;
    const seen = new Set();
    pack.scene.traverse((o) => {
      if (o.geometry && !seen.has(o.geometry)) { seen.add(o.geometry); o.geometry.dispose(); }
      const mats = Array.isArray(o.material) ? o.material : o.material ? [o.material] : [];
      for (const m of mats) {
        if (seen.has(m)) continue;
        seen.add(m);
        for (const k of MAP_KEYS) if (m[k] && !seen.has(m[k])) { seen.add(m[k]); m[k].dispose(); }
        m.dispose();
      }
    });
  };
  if (entry.pack) kill(entry.pack);
  else entry.promise.then(kill, () => {});
}

/**
 * Point EMI_glass at the .glb's SIBLING emi-faces.png instead of the strip packed inside it.
 * The pack ships a BAKED_FRAMES-wide strip; the live one grows a frame at a time, so the glb is
 * never rebaked and the loader re-points the sampler here. Everything else about the material is
 * left alone: flipY, colour space, the UV channel and wrapT all come off the embedded texture, so
 * only the width of one frame changes. A miss (no glass, no map, a 404) resolves false and the
 * embedded strip stays, which is why setFace reads the frame count off the texture rather than
 * off FACES: a fallback atlas is still five frames wide and indices past it clamp. That fallback
 * gets padded in place (hardenAtlas) so the phone-safe sampler holds either way.
 * The orphaned embedded texture is never uploaded (the swap lands before the pack resolves), so
 * it costs nothing on the GPU and is disposed here rather than left for disposePack to find.
 */
function swapFaceAtlas(pack) {
  if (!pack || !pack.scene || !pack.url) return Promise.resolve(false);
  let mesh = null;
  pack.scene.traverse((o) => { if (!mesh && o.isMesh && o.name === GLASS) mesh = o; });
  if (!mesh) return Promise.resolve(false);
  const mats = Array.isArray(mesh.material) ? mesh.material : mesh.material ? [mesh.material] : [];
  const slots = [];
  for (const m of mats) for (const key of ['map', 'emissiveMap']) if (m && m[key]) slots.push({ m, key });
  if (!slots.length) return Promise.resolve(false);
  const url = pack.url.replace(/[^/]+$/, FACE_ATLAS);
  return new Promise((resolve) => {
    new THREE.TextureLoader().load(url, resolve, undefined, () => resolve(null));
  }).then((tex) => {
    const src = slots[0].m[slots[0].key];
    if (!tex) { hardenAtlas(slots, src, src.repeat.x, 0); return false; }   // no sibling png: pad the baked strip
    const wide = src.repeat.x * BAKED_FRAMES / FACES.length;               // one live frame over the authored UVs
    const potted = padAtlasToPot(src, tex.image, wide, FACES.length);
    if (potted) { tex.dispose(); for (const slot of slots) { slot.m[slot.key] = potted; slot.m.needsUpdate = true; } src.dispose(); return true; }
    tex.flipY = src.flipY;                       // glTF images are not flipped; TextureLoader's are
    tex.colorSpace = src.colorSpace;
    tex.channel = src.channel;
    tex.center.copy(src.center); tex.rotation = src.rotation;
    tex.wrapS = THREE.RepeatWrapping; tex.wrapT = src.wrapT;
    tex.magFilter = THREE.NearestFilter; tex.minFilter = THREE.NearestFilter;
    tex.generateMipmaps = false;
    tex.repeat.set(wide, src.repeat.y);
    tex.offset.set(0, src.offset.y);
    tex.userData.faceFrames = FACES.length;
    tex.needsUpdate = true;
    for (const slot of slots) { slot.m[slot.key] = tex; slot.m.needsUpdate = true; }
    return true;
  }).catch(() => false);
}

/** Pad whatever strip a material already carries and put it back in the same slots. Returns
 *  nothing: the caller's true/false is about the sibling atlas, not about this. */
function hardenAtlas(slots, src, repeatX, frames) {
  const potted = padAtlasToPot(src, src.image, repeatX, frames);
  if (!potted) return;
  for (const slot of slots) { slot.m[slot.key] = potted; slot.m.needsUpdate = true; }
  src.dispose();
}

// ---- merge to a roomProps-shaped instance geometry --------------------------------------

/**
 * Flatten every mesh under `node` into ONE geometry in `node`'s local frame, with a flat
 * per-vertex colour, exactly the shape voxel() produces: attributes position + normal + color,
 * ready for `new THREE.InstancedMesh(geo, new THREE.MeshLambertMaterial({ vertexColors: true }), n)`.
 *
 * Colour source per mesh: COLOR_0 if the mesh has one, else the material's base color, both
 * already linear (see the header). Meshes whose material is named `outline` are inverted hulls:
 * they come through untouched, winding included. Everything else gets its index re-wound when
 * its baked matrix mirrors, so it still lights right.
 *
 * Nothing shared is disposed: the per-mesh copies are throwaway clones and only those go.
 */
export function toInstanceGeometry(node) {
  if (!node) return null;
  node.updateWorldMatrix(true, true);
  _inv.copy(node.matrixWorld).invert();
  const parts = [];
  let anyNonIndexed = false;
  node.traverse((o) => {
    if (!o.isMesh || !o.geometry || !o.geometry.attributes || !o.geometry.attributes.position) return;
    if (o.visible === false) return;
    const g = o.geometry.clone();
    for (const key of Object.keys(g.attributes)) {
      if (key !== 'position' && key !== 'normal' && key !== 'color') g.deleteAttribute(key);
    }
    if (!g.attributes.normal) g.computeVertexNormals();
    _mat.multiplyMatrices(_inv, o.matrixWorld);
    g.applyMatrix4(_mat);
    if (_mat.determinant() < 0 && !isOutline(o.material)) flipWinding(g);
    if (!g.attributes.color) g.setAttribute('color', flatColor(o.material, g.attributes.position.count));
    else normalizeColor(g);
    g.morphAttributes = {};
    g.clearGroups();
    if (!g.index) anyNonIndexed = true;
    parts.push(g);
  });
  if (!parts.length) return null;
  const ready = anyNonIndexed ? parts.map((g) => (g.index ? g.toNonIndexed() : g)) : parts;
  const merged = ready.length === 1 ? ready[0].clone() : mergeGeometries(ready, false);
  for (const g of ready) if (!parts.includes(g)) g.dispose();
  for (const g of parts) g.dispose();
  if (merged) merged.computeBoundingSphere();
  return merged;
}

function isOutline(material) {
  const mats = Array.isArray(material) ? material : material ? [material] : [];
  return mats.some((m) => m && m.name === OUTLINE);
}

/** Reverse each triangle's winding in place (index only: positions and normals are already baked). */
function flipWinding(g) {
  if (!g.index) g.setIndex(Array.from({ length: g.attributes.position.count }, (_, i) => i));
  const a = g.index.array;
  for (let i = 0; i + 2 < a.length; i += 3) { const t = a[i]; a[i] = a[i + 2]; a[i + 2] = t; }
  g.index.needsUpdate = true;
}

/** One flat colour repeated per vertex, taken from the material (linear, see the header). */
function flatColor(material, count) {
  const m = Array.isArray(material) ? material[0] : material;
  const c = m && m.color ? m.color : null;
  const r = c ? c.r : 1, gg = c ? c.g : 1, b = c ? c.b : 1;
  const arr = new Float32Array(count * 3);
  for (let i = 0; i < count; i++) { arr[i * 3] = r; arr[i * 3 + 1] = gg; arr[i * 3 + 2] = b; }
  return new THREE.BufferAttribute(arr, 3);
}

/** COLOR_0 may arrive as RGBA or as normalized bytes; the merge wants a plain float RGB. */
function normalizeColor(g) {
  const src = g.attributes.color;
  if (src.itemSize === 3 && src.array instanceof Float32Array && !src.normalized) return;
  const n = src.count;
  const arr = new Float32Array(n * 3);
  for (let i = 0; i < n; i++) { arr[i * 3] = src.getX(i); arr[i * 3 + 1] = src.getY(i); arr[i * 3 + 2] = src.getZ(i); }
  g.setAttribute('color', new THREE.BufferAttribute(arr, 3));
}

// ---- rig flatten: one draw per animated node and material -------------------------------

/**
 * Bake a rig down to one mesh per (animated pivot, material). A Blender export arrives as one
 * mesh per part (emi.glb: 69 primitives, so 69 draw calls per EMI on screen); only the nodes a
 * clip drives ever move, so every static part under a pivot can share one buffer with its
 * siblings of the same material and still animate right. Rules:
 *   - the pivot set = every node any clip in `animations` targets, plus `root` and `keep`
 *   - a mesh whose material carries a texture stays as it is (the face glass and its atlas)
 *   - a mesh named in `keep`, or that is itself a pivot, stays as it is
 *   - the merged mesh hangs off the first contributor's parent (static under the pivot by
 *     construction), so names like EMI_case / ball keep resolving to a node that holds geometry
 *   - outline hulls keep their winding; mirrored bakes of everything else are re-wound
 * Returns { before, after }: mesh counts. Safe to call twice (the second pass finds nothing).
 */
export function flattenRig(root, animations = [], { keep = [] } = {}) {
  const out = { before: 0, after: 0 };
  if (!root || !root.traverse) return out;
  const pivots = new Set(keep);
  for (const clip of animations || []) for (const t of clip.tracks || []) {
    const name = THREE.PropertyBinding.parseTrackName(t.name).nodeName;
    if (name) pivots.add(name);
  }
  const isPivot = (o) => o === root || pivots.has(o.name);
  const pivotOf = (o) => { let p = o.parent; while (p && p !== root && !isPivot(p)) p = p.parent; return p || root; };
  root.updateWorldMatrix(true, true);
  const groups = new Map();                   // pivot -> Map(material -> { host, name, parts, nonIndexed })
  const dead = [];
  root.traverse((o) => {
    if (!o.isMesh || !o.geometry || !o.geometry.attributes || !o.geometry.attributes.position) return;
    if (o.visible === false || isPivot(o) || Array.isArray(o.material) || !o.material) return;
    if (MAP_KEYS.some((k) => o.material[k])) return;
    const pivot = pivotOf(o);
    const host = o.parent || pivot;
    let byMat = groups.get(pivot);
    if (!byMat) groups.set(pivot, (byMat = new Map()));
    let part = byMat.get(o.material);
    if (!part) byMat.set(o.material, (part = { host, name: o.name, parts: [], nonIndexed: false, shadow: o.castShadow }));
    const g = o.geometry.clone();
    for (const key of Object.keys(g.attributes)) if (key !== 'position' && key !== 'normal') g.deleteAttribute(key);
    if (!g.attributes.normal) g.computeVertexNormals();
    _inv.copy(part.host.matrixWorld).invert();
    _mat.multiplyMatrices(_inv, o.matrixWorld);
    g.applyMatrix4(_mat);
    if (_mat.determinant() < 0 && !isOutline(o.material)) flipWinding(g);
    g.morphAttributes = {};
    g.clearGroups();
    if (!g.index) part.nonIndexed = true;
    part.parts.push(g);
    dead.push(o);
  });
  out.before = dead.length;
  for (const byMat of groups.values()) for (const [material, part] of byMat) {
    const ready = part.nonIndexed ? part.parts.map((g) => (g.index ? g.toNonIndexed() : g)) : part.parts;
    const merged = ready.length === 1 ? ready[0] : mergeGeometries(ready, false);
    for (const g of ready) if (g !== merged && !part.parts.includes(g)) g.dispose();
    for (const g of part.parts) if (g !== merged) g.dispose();
    if (!merged) continue;
    merged.computeBoundingSphere();
    const m = new THREE.Mesh(merged, material);
    m.name = part.name;
    m.castShadow = part.shadow;
    part.host.add(m);
    out.after++;
  }
  for (const o of dead) {
    if (o.children.length) {                  // a mesh with children becomes a plain node, kids kept
      const g = new THREE.Group();
      g.name = o.name; g.position.copy(o.position); g.quaternion.copy(o.quaternion); g.scale.copy(o.scale);
      while (o.children.length) g.add(o.children[0]);
      o.parent.add(g);
    }
    o.removeFromParent();
  }
  return out;
}

// ---- the face atlas ---------------------------------------------------------------------

/** How many frames the strip on this texture holds: what swapFaceAtlas tagged it with, or the
 *  BAKED_FRAMES of the strip inside the glb if the swap never happened. */
export function faceFrames(tex) {
  const n = tex && tex.userData && tex.userData.faceFrames;
  return n > 0 ? n : BAKED_FRAMES;
}

const ONE_SCALE = { x: 1, y: 1 };
const MAX_ATLAS_POT = 4096;    // past this we would be trading a white face for an out of memory

/** The (x, y) the frame math is squeezed by once the strip sits in a padded texture, or 1, 1 when
 *  it is still the raw strip. Exported for the smoke; setFace is the only caller that matters. */
export function atlasScale(tex) {
  const s = tex && tex.userData && tex.userData.atlasScale;
  return s && s.x > 0 && s.y > 0 ? s : ONE_SCALE;
}

function potCeil(n) { return Math.pow(2, Math.ceil(Math.log2(Math.max(1, n)))); }

/**
 * Redraw a face strip into a POWER OF TWO CanvasTexture and hand back a texture that is legal
 * under the strictest sampler rules there are, and whose pixels live in a <canvas>.
 *
 * WHY. emi_glass carries the atlas on emissiveMap with an emissive factor of 1,1,1 and no base
 * map at all, so anything that makes that one sample come back blank paints the glass a SOLID
 * WHITE RECTANGLE, which is what the owner's iPhone shows on the home screen. Two things fed
 * that, and this kills both:
 *   1. setFace used to flag the texture needsUpdate on every frame change, and a source version
 *      bump makes three re-upload the whole image. Measured: 21 face changes, 21 full
 *      texSubImage2D calls of the 1064x137 strip. Mobile Safari is free to drop the decoded
 *      bitmap of an <img> that is not in the document once it wants the memory back, and a
 *      re-upload after that hands GL nothing. A canvas keeps its own backing store, and setFace
 *      no longer asks for a re-upload at all.
 *   2. 1064x137 is not a power of two, and the strip was sampled with RepeatWrapping. That pair
 *      is illegal on a WebGL1 context (NPOT wants clamp to edge, no mipmaps and a non mipmapping
 *      min filter) and is the kind of thing a driver is allowed to be unhappy about. Padded and
 *      clamped, nothing about this sampler is exotic anywhere.
 *
 * The frame math rides along. The strip goes in the corner that ends up at uv 0,0 whichever way
 * flipY points, so repeat and offset scale by the same (w/W, h/H) and every sampled uv stays
 * inside the strip: EMI_glass's authored u span is 0.0007 .. 0.1993 and the widest frame window
 * lands at 0.9995 before padding, so no wrap mode is ever exercised in the first place.
 *
 * Returns null (caller keeps the raw strip) with nothing to draw on (the node smoke), on a
 * source carrying a uv transform we would have to compose with, or on a silly padded size.
 */
function padAtlasToPot(src, image, repeatX, frames) {
  if (typeof document === 'undefined' || !document.createElement) return null;
  const w = image && (image.width || image.naturalWidth), h = image && (image.height || image.naturalHeight);
  if (!w || !h) return null;
  if (src.center.x !== 0 || src.center.y !== 0 || src.rotation !== 0) return null;
  const W = potCeil(w), H = potCeil(h);
  if (W > MAX_ATLAS_POT || H > MAX_ATLAS_POT) return null;
  let canvas;
  try {
    canvas = document.createElement('canvas');
    canvas.width = W; canvas.height = H;
    const ctx = canvas.getContext('2d', { willReadFrequently: false });
    if (!ctx) return null;
    // flipY flips the whole upload, so the strip goes wherever it ends up at the uv origin
    ctx.drawImage(image, 0, src.flipY ? H - h : 0, w, h);
  } catch (e) { return null; }                 // an undrawable or tainted source is not worth a throw
  const sx = w / W, sy = h / H;
  const tex = new THREE.CanvasTexture(canvas);
  tex.flipY = src.flipY;                       // glTF images are not flipped; a loaded png is
  tex.colorSpace = src.colorSpace;
  tex.channel = src.channel;
  tex.wrapS = THREE.ClampToEdgeWrapping;       // the sampled uv never leaves the strip, so clamping
  tex.wrapT = THREE.ClampToEdgeWrapping;       // costs nothing and is legal on every context there is
  tex.magFilter = THREE.NearestFilter;
  tex.minFilter = THREE.NearestFilter;         // Nearest takes no mipmaps, which is the other NPOT rule
  tex.generateMipmaps = false;
  tex.repeat.set(repeatX * sx, src.repeat.y * sy);
  tex.offset.set(0, src.offset.y * sy);
  tex.userData.atlasScale = { x: sx, y: sy };
  if (frames > 0) tex.userData.faceFrames = frames;
  return tex;
}

/**
 * Point EMI_glass's map at one atlas frame. The atlas is a horizontal strip and the authored UVs
 * span frame 0 of the BAKED strip, so the frame width is already in the mesh (plus the repeat.x
 * swapFaceAtlas set) and all we move is the offset. An index past the end of the strip actually
 * loaded clamps to its last frame. Returns true if a glass mesh with a map was found.
 *
 * The offset is a uniform, not pixels, so NOTHING here flags the texture needsUpdate: that used
 * to re-upload the whole atlas on every single face change (see padAtlasToPot). A raw strip that
 * never went through padAtlasToPot still gets its sampler forced, but only once, and only when
 * something is actually wrong with it, because sampler state only lands on an upload.
 */
export function setFace(model, index) {
  if (!model || !model.traverse) return false;
  let mesh = null;
  model.traverse((o) => { if (!mesh && o.isMesh && o.name === GLASS) mesh = o; });
  if (!mesh) return false;
  const mats = Array.isArray(mesh.material) ? mesh.material : mesh.material ? [mesh.material] : [];
  let hit = false;
  // the atlas may ride the base map or the emissive map (emi.glb puts it on the emissive
  // slot so the screen stays self-lit); shift whichever the material carries
  for (const m of mats) for (const key of ['map', 'emissiveMap']) {
    const tex = m && m[key];
    if (!tex) continue;
    forceAtlasSampler(tex);
    const n = faceFrames(tex);
    tex.offset.x = (Math.min(n - 1, Math.max(0, index | 0)) / n) * atlasScale(tex).x;
    hit = true;
  }
  return hit;
}

/** A strip that never went through padAtlasToPot (the node smoke, a browser with no 2D canvas)
 *  still wants the sampler a bare atlas needs. One upload, and only if it is not already right. */
export function forceAtlasSampler(tex) {
  if (!tex || (tex.userData && tex.userData.atlasScale)) return;
  if (tex.wrapS === THREE.RepeatWrapping && tex.magFilter === THREE.NearestFilter
    && tex.minFilter === THREE.NearestFilter && tex.generateMipmaps === false) return;
  tex.wrapS = THREE.RepeatWrapping;
  tex.magFilter = THREE.NearestFilter;
  tex.minFilter = THREE.NearestFilter;
  tex.generateMipmaps = false;
  tex.needsUpdate = true;                   // sampler state only lands on an upload
}

// ---- the pixel pass ---------------------------------------------------------------------

/** Run every texture on `model` through the pixelizer so it snaps to NearestFilter with the
 *  rest of the world while a block size is on. No pixelizer, nothing to do. */
export function preparePixel(model, pixel) {
  if (!model || !model.traverse || !pixel || !pixel.filterTexture) return;
  model.traverse((o) => {
    const mats = Array.isArray(o.material) ? o.material : o.material ? [o.material] : [];
    for (const m of mats) {
      for (const k of MAP_KEYS) if (m[k]) pixel.filterTexture(m[k]);
      if (m.uniforms) for (const u of Object.values(m.uniforms)) if (u && u.value && u.value.isTexture) pixel.filterTexture(u.value);
    }
  });
}

