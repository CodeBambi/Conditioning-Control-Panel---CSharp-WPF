/* ============================================================================
 * test/gen-i18n-en.js - writes i18n/en.js from the English copy decks.
 *
 *   node test/gen-i18n-en.js
 *
 * Run it after any copy change in ui/strings.js or another deck listed in
 * i18n/decks.js. test/selftest-i18n.js fails until you do, and then names the
 * keys the eight translations are now missing or still carrying.
 * ==========================================================================*/

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { flattenDeck } from '../core/i18n.js';
import { DECKS } from '../i18n/decks.js';

export function englishEntries() {
  const out = [];
  for (const [prefix, raw] of DECKS) flattenDeck(prefix, raw, out);
  return out;
}

export function renderTable(entries, header) {
  const lines = [header, '', 'export default Object.freeze({'];
  for (const [k, v] of entries) lines.push('  ' + k + ': ' + JSON.stringify(v) + ',');
  lines.push('});', '');
  return lines.join('\n');
}

const HEADER = '/* i18n/en.js - GENERATED by test/gen-i18n-en.js from the copy decks in\n'
  + ' * i18n/decks.js. Do not edit by hand: change the English in the deck, then\n'
  + ' * run `node test/gen-i18n-en.js`. */';

const self = fileURLToPath(import.meta.url);
if (process.argv[1] && path.resolve(process.argv[1]) === self) {
  const entries = englishEntries();
  const seen = new Set();
  for (const [k] of entries) {
    if (seen.has(k)) { console.error('duplicate key ' + k); process.exit(1); }
    seen.add(k);
  }
  const target = path.join(path.dirname(self), '..', 'i18n', 'en.js');
  fs.writeFileSync(target, renderTable(entries, HEADER));
  console.log('i18n/en.js: ' + entries.length + ' keys');
}
